// Regenerates the module-graph section of docs/architecture.md from real import statements.
//   npm run architecture          -> rewrite the generated block in docs/architecture.md
//   npm run architecture -- --print -> print it instead
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC = path.join(root, "src");
const DOC = path.join(root, "docs", "architecture.md");
const exts = [".ts", ".tsx", ".js", ".mjs", ".css"];

const walk = (dir) =>
  fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(dir, e.name)) : [path.join(dir, e.name)]));
const rel = (f) => path.relative(root, f).split(path.sep).join("/");

const files = [...walk(SRC), ...walk(path.join(root, "scripts"))].filter((f) => /\.(tsx?|mjs|css)$/.test(f));
const known = new Set(files.map(rel));

function resolve(from, spec) {
  const base = spec.startsWith("@/") ? path.join(SRC, spec.slice(2)) : spec.startsWith(".") ? path.resolve(path.dirname(from), spec) : null;
  if (!base) return null;
  const hit = [base, ...exts.map((e) => base + e), ...exts.map((e) => path.join(base, "index" + e))].map(rel).find((c) => known.has(c));
  return hit ?? null;
}

const importRe = /(?:import|export)\s+(?:type\s+)?(?:[^'"`;]*?\s+from\s+)?["']([^"']+)["']|import\(\s*["']([^"']+)["']\s*\)/g;
const cssRe = /@(?:import|config|plugin)\s+["']([^"']+)["']/g;

const nodes = {};
const edges = new Set();
const external = new Set();
for (const f of files) {
  const r = rel(f);
  const src = fs.readFileSync(f, "utf8");
  nodes[r] = { client: /^\s*["']use client["']/.test(src) };
  for (const m of src.matchAll(r.endsWith(".css") ? cssRe : importRe)) {
    const spec = m[1] ?? m[2];
    if (!spec) continue;
    const to = resolve(f, spec);
    if (to && to !== r) edges.add(`${r}>${to}`);
    else if (!to && !spec.startsWith(".") && !spec.startsWith("@/") && !spec.startsWith("node:")) {
      external.add(spec.startsWith("@") ? spec.split("/").slice(0, 2).join("/") : spec.split("/")[0]);
    }
  }
}
const pairs = [...edges].map((e) => e.split(">"));

const layer = (f) => {
  const p = f.split("/");
  if (p[0] === "scripts") return "scripts";
  if (p[1] === "app") return "app";
  if (p[1] === "components") return p[3] ? `components/${p[2]}` : "components/(root)";
  return p[1];
};
const id = (l) => l.replace(/[^a-z]/gi, "_");

// layer -> layer edge counts (self-edges dropped)
const counts = {};
for (const [a, b] of pairs) {
  const k = `${layer(a)}>${layer(b)}`;
  if (layer(a) !== layer(b)) counts[k] = (counts[k] ?? 0) + 1;
}
const layers = [...new Set(Object.values(nodes).length ? Object.keys(nodes).map(layer) : [])].sort();
const size = (l) => Object.keys(nodes).filter((f) => layer(f) === l).length;

// cycles (DFS)
const adj = {};
for (const [a, b] of pairs) (adj[a] ??= []).push(b);
const state = {};
const stack = [];
const cycles = [];
const dfs = (n) => {
  state[n] = 1;
  stack.push(n);
  for (const m of adj[n] ?? []) {
    if (state[m] === 1) cycles.push([...stack.slice(stack.indexOf(m)), m]);
    else if (!state[m]) dfs(m);
  }
  stack.pop();
  state[n] = 2;
};
Object.keys(nodes).forEach((n) => !state[n] && dfs(n));

const fanIn = {};
for (const [, b] of pairs) fanIn[b] = (fanIn[b] ?? 0) + 1;
const hubs = Object.entries(fanIn).sort((a, b) => b[1] - a[1]).slice(0, 8);

const pkg = JSON.parse(fs.readFileSync(path.join(root, "package.json"), "utf8"));
const unused = Object.keys(pkg.dependencies).filter((d) => !external.has(d));
const tsx = Object.keys(nodes).filter((f) => f.endsWith(".tsx"));
const clients = tsx.filter((f) => nodes[f].client);

const md = [
  `_${Object.keys(nodes).length} modules, ${pairs.length} internal imports, ${external.size} external packages. Generated by \`npm run architecture\`._`,
  "",
  "```mermaid",
  "flowchart LR",
  ...layers.map((l) => `  ${id(l)}["${l}<br/>${size(l)} ${size(l) === 1 ? "file" : "files"}"]`),
  ...Object.entries(counts)
    .sort()
    .map(([k, n]) => {
      const [a, b] = k.split(">");
      return `  ${id(a)} -->|${n}| ${id(b)}`;
    }),
  "```",
  "",
  `- **Import cycles:** ${cycles.length ? cycles.map((c) => c.join(" -> ")).join("; ") : "none"}`,
  `- **Client vs server:** ${clients.length} of ${tsx.length} \`.tsx\` modules are \`"use client"\``,
  `- **Declared but never imported:** ${unused.length ? unused.map((u) => `\`${u}\``).join(", ") : "none"}`,
  "- **Most depended-on modules (fan-in):** " + hubs.map(([f, n]) => `\`${f.replace("src/", "")}\` (${n})`).join(", "),
].join("\n");

const START = "<!-- generated:start -->";
const END = "<!-- generated:end -->";
if (process.argv.includes("--print") || !fs.existsSync(DOC)) {
  console.log(md);
} else {
  const doc = fs.readFileSync(DOC, "utf8");
  const a = doc.indexOf(START);
  const b = doc.indexOf(END);
  if (a < 0 || b < a) throw new Error(`${DOC} is missing the ${START} / ${END} markers`);
  fs.writeFileSync(DOC, `${doc.slice(0, a + START.length)}\n${md}\n${doc.slice(b)}`);
  console.log(`Updated ${rel(DOC)}`);
}
